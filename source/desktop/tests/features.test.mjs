test('extractFrontmatter parses key/value, arrays, zero-indent lists, trailing spaces and ignores invalid blocks', () => {
  const doc = [
    '---  ',
    'title: "Architecture Spec"',
    'author: Kenny',
    'tags: [offline, "markdown", windows]',
    'reviewers:',
    '- Alice',
    '- "Bob"',
    'empty_key:',
    'quote_char: "',
    '# comment line',
    '--- ',
    '',
    '# Body Heading',
    'Hello world.',
  ].join('\n');

  const res = extractFrontmatter(doc);
  assert.deepEqual(res.metadata, [
    { key: 'title', value: 'Architecture Spec' },
    { key: 'author', value: 'Kenny' },
    { key: 'tags', value: 'offline, markdown, windows' },
    { key: 'reviewers', value: 'Alice, Bob' },
    { key: 'quote_char', value: '"' },
  ]);
  assert.equal(res.body, '# Body Heading\nHello world.');

  // Empty key followed by another key and stray list item must not leak into the previous empty key.
  const strayList = '---\ntags:\ntitle: My Doc\n  - stray\n---\nBody';
  assert.deepEqual(extractFrontmatter(strayList), { metadata: [], body: strayList });

  // Regular horizontal rule with non-YAML body must stay untouched.
  const hr = '---\nJust a paragraph\n---\nMore text';
  assert.deepEqual(extractFrontmatter(hr), { metadata: [], body: hr });

  // Unclosed frontmatter must stay untouched.
  const unclosed = '---\ntitle: Unclosed\n# Still body';
  assert.deepEqual(extractFrontmatter(unclosed), { metadata: [], body: unclosed });

  // Frontmatter ending at EOF with no trailing newline.
  const eofOnly = '---\nstatus: draft\n---';
  const eofRes = extractFrontmatter(eofOnly);
  assert.deepEqual(eofRes.metadata, [{ key: 'status', value: 'draft' }]);
  assert.equal(eofRes.body, '');
});

test('parseGitHubAlert recognizes all 5 alert kinds and rejects adjacent non-whitespace text', () => {
  for (const [token, kind, label] of [
    ['[!NOTE]\nUseful detail', 'note', 'Note'],
    ['[!tip] Quick shortcut', 'tip', 'Tip'],
    ['[!IMPORTANT]\nMust read', 'important', 'Important'],
    ['[!WARNING]\nCareful here', 'warning', 'Warning'],
    ['[!CAUTION]\nDestructive action', 'caution', 'Caution'],
    ['[!NOTE]', 'note', 'Note'],
  ]) {
    const parsed = parseGitHubAlert(token);
    assert.ok(parsed, token);
    assert.equal(parsed.kind, kind);
    assert.equal(parsed.label, label);
  }
  assert.equal(parseGitHubAlert('[!NOTE]word'), null);
  assert.equal(parseGitHubAlert('[!UNKNOWN]\nNope'), null);
  assert.equal(parseGitHubAlert('Regular blockquote text'), null);
});

test('live-diff strips frontmatter comments, ignores fenced code, and normalizes inline heading syntax', () => {
  const before = [
    '---',
    '# generated by agent v1',
    'title: Plan',
    '---',
    '',
    '# Overview',
    'Intro text.',
    '',
    '## `API` **Changes** and [Docs](./docs.md)',
    'Old endpoint.',
    '',
    '## Code Example',
    '```bash',
    '# Not a real heading inside fence',
    'echo hi',
    '```',
  ].join('\n');

  const sections = splitMarkdownSections(before);
  assert.deepEqual(sections.map(s => s.heading), ['Overview', 'API Changes and Docs', 'Code Example']);
  assert.equal(normalizeHeadingText('`API` **Changes** and [Docs](./docs.md)'), 'API Changes and Docs');

  const after = before
    .replace('# generated by agent v1', '# generated by agent v2')
    .replace('Old endpoint.', 'New endpoint.');
  const diff = diffDocumentSections(before, after);
  assert.equal(diff.changedCount, 1);
  assert.deepEqual(diff.changedHeadings, ['API Changes and Docs']);

  // Unchanged document reports zero changes.
  const same = diffDocumentSections(before, before);
  assert.equal(same.changedCount, 0);
  assert.deepEqual(same.changedHeadings, []);

  // Added new section reports it cleanly.
  const added = after + '\n\n## Next Steps\nShip v2.1.0.\n';
  const addedDiff = diffDocumentSections(after, added);
  assert.equal(addedDiff.changedCount, 1);
  assert.deepEqual(addedDiff.changedHeadings, ['Next Steps']);
});

test('serializeTable produces RFC-4180 CSV and clean single-row TSV', () => {
  const rows = [
    ['Name', 'Notes', 'Score'],
    ['Alpha, Inc.', 'Line 1\nLine 2 "quoted"', '98.5'],
    ['Beta\tLab', 'Plain', '99.1'],
  ];
  assert.equal(
    serializeTable(rows, 'csv'),
    'Name,Notes,Score\n"Alpha, Inc.","Line 1\nLine 2 ""quoted""",98.5\nBeta\tLab,Plain,99.1',
  );
  assert.equal(
    serializeTable(rows, 'tsv'),
    'Name\tNotes\tScore\nAlpha, Inc.\tLine 1 Line 2 "quoted"\t98.5\nBeta Lab\tPlain\t99.1',
  );
});

